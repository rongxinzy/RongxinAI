// @vitest-environment jsdom
import { render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { createElement } from 'react';
import { beforeEach, expect, test } from 'vitest';
import { i18nService } from '../../services/i18n';
import type { CoworkMessage } from '../../types/cowork';
import { SessionStatsLine } from './SessionStatsLine';

beforeEach(() => i18nService.setLanguage('en', { persist: false }));

const messages: CoworkMessage[] = [
  { id: 'user', type: 'user', content: 'Review this file', timestamp: 1 },
  {
    id: 'answer',
    type: 'assistant',
    content: 'Reviewed',
    timestamp: 2,
    metadata: {
      usage: { inputTokens: 100, outputTokens: 30, cacheReadTokens: 20, cacheWriteTokens: 0 },
      metrics: { requestStartedAt: 1000, firstVisibleTextAt: 1400, completedAt: 3000 },
    },
  },
  {
    id: 'tool',
    type: 'tool_result',
    content: 'File contents',
    timestamp: 3,
    metadata: { metrics: { toolDurationMs: 900 } },
  },
];

function metric(label: string): string | null {
  return (
    within(screen.getByTestId('session-run-info')).getByText(label).nextElementSibling
      ?.textContent ?? null
  );
}

test('keeps every reported metric behind a keyboard-accessible disclosure and restores focus', async () => {
  const user = userEvent.setup();
  render(createElement(SessionStatsLine, { messages }));
  const trigger = screen.getByRole('button', { name: 'Run details' });
  expect(screen.queryByTestId('session-run-info')).toBeNull();
  expect(screen.queryByText('Content generated by AI, for reference only.')).toBeNull();
  await user.tab();
  expect(trigger).toHaveFocus();
  await user.keyboard('{Enter}');
  expect(metric('Conversation turns')).toBe('1');
  expect(metric('Execution steps')).toBe('2');
  expect(metric('Model time')).toBe('2s');
  expect(metric('Tool time')).toBe('900ms');
  expect(metric('Average first response')).toBe('400ms');
  expect(metric('Generation speed')).toBe('18.8 tok/s');
  expect(metric('Cache hit rate')).toBe('17%');
  expect(metric('Input tokens')).toBe('100');
  expect(metric('Output tokens')).toBe('30');
  expect(screen.getByText('Content generated by AI, for reference only.')).toBeVisible();
  await user.keyboard('{Escape}');
  expect(screen.queryByTestId('session-run-info')).toBeNull();
  expect(trigger).toHaveFocus();
  await user.keyboard(' ');
  expect(metric('Input tokens')).toBe('100');
  await user.keyboard('{Escape}');
  expect(trigger).toHaveFocus();
});

test('updates an open disclosure without replacing missing usage with zero', async () => {
  const user = userEvent.setup();
  const view = render(createElement(SessionStatsLine, { messages: messages.slice(0, 1) }));
  await user.click(screen.getByRole('button', { name: 'Run details' }));
  expect(metric('Execution steps')).toBe('0');
  expect(screen.queryByText('Input tokens')).toBeNull();
  expect(screen.queryByText('Cache hit rate')).toBeNull();
  view.rerender(createElement(SessionStatsLine, { messages }));
  expect(metric('Input tokens')).toBe('100');
  expect(metric('Execution steps')).toBe('2');
  view.rerender(
    createElement(SessionStatsLine, {
      messages: [
        {
          ...messages[1],
          metadata: {
            usage: { inputTokens: 5, outputTokens: 0, cacheReadTokens: 0, cacheWriteTokens: 0 },
          },
        },
      ],
    }),
  );
  expect(metric('Output tokens')).toBe('0');
  expect(metric('Cache hit rate')).toBe('0%');
  expect(screen.queryByText('Model time')).toBeNull();
});

test('does not show a run-details control before there are any metrics', () => {
  render(createElement(SessionStatsLine, { messages: [] }));
  expect(screen.queryByRole('button')).toBeNull();
});
