import { readFileSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

import { generateAllThemesCSS } from '../engine/css-generator';
import { allThemes } from '../themes/index';
import { themePlugins } from '../themes/plugins';

const presentations = themePlugins.map(({ id, name, appearances }) => ({
  id,
  name,
  appearances: {
    light: { id: appearances.light.meta.id, background: appearances.light.background ?? null },
    dark: { id: appearances.dark.meta.id, background: appearances.dark.background ?? null },
  },
}));
const themeDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputs = {
  'css/themes.css': generateAllThemesCSS(allThemes),
  'themes/presentations.generated.ts':
    '// Generated by theme:generate.\n// oxfmt-ignore\n' +
    `export const themePresentations = ${JSON.stringify(presentations)} as const;\n`,
};
for (const [relativePath, content] of Object.entries(outputs)) {
  const outPath = resolve(themeDir, relativePath);
  if (process.argv.includes('--check')) {
    const checkedIn = readFileSync(outPath, 'utf8').replace(/\r\n?/g, '\n');
    if (checkedIn !== content) throw new Error(`${relativePath} is stale. Run theme:generate.`);
  } else {
    writeFileSync(outPath, content, 'utf-8');
  }
  console.log(`${relativePath} (${Buffer.byteLength(content)} bytes)`);
}
