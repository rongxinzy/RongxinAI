import { generateComponentCSS } from '../components/css';
import { validateTheme } from '../themes/plugins';
import type { ThemeDefinition } from '../themes/types';
import { TOKEN_CONTRACT, TOKEN_NAMES } from '../tokens/contract';

/** Token block for one theme: color-scheme plus every contract token. */
function themeTokenBlock(theme: ThemeDefinition): string {
  const vars = TOKEN_NAMES.map(name => `  ${TOKEN_CONTRACT[name]}: ${theme.tokens[name]};`).join(
    '\n',
  );
  const colorScheme = theme.meta.appearance === 'dark' ? 'dark' : 'light';
  return `  color-scheme: ${colorScheme};\n${vars}`;
}

/**
 * Generate a single theme's standalone CSS: its token block plus the shared
 * component rules scoped to that theme. Used by the live theme manager for
 * hot-switch injection (one active theme at a time); component rules are
 * appearance-independent, so only the scope-hashed motion names vary per
 * theme.
 */
export function generateThemeCSS(theme: ThemeDefinition): string {
  validateTheme(theme);
  return `[data-theme="${theme.meta.id}"] {\n${themeTokenBlock(theme)}\n}\n${generateComponentCSS(theme.components, `[data-theme="${theme.meta.id}"]`)}`;
}

/** Scope under which the shared component ruleset is emitted once. */
const UNIVERSAL_COMPONENT_SCOPE = ':where(:root, [data-theme])';

/**
 * Generate the full CSS for all themes (work package N).
 *
 * Component rules are appearance-independent (every light/dark difference
 * lives in `state-*` tokens), so they are emitted exactly once under a
 * universal scope that matches every theme — and the no-attribute default —
 * instead of once per theme. Per-theme blocks carry only tokens and
 * color-scheme. The first theme is merged with :root to avoid duplication.
 *
 * Diverging component recipes across themes are a contract violation (the
 * differences would be silently dropped here), so they fail generation.
 */
export function generateAllThemesCSS(themes: ThemeDefinition[]): string {
  themes.forEach(validateTheme);
  if (themes.length === 0) return '';

  const [defaultTheme, ...restThemes] = themes;
  const rootBlock = `:root, [data-theme="${defaultTheme.meta.id}"] {\n${themeTokenBlock(defaultTheme)}\n}`;
  const restBlocks = restThemes
    .map(theme => `[data-theme="${theme.meta.id}"] {\n${themeTokenBlock(theme)}\n}`)
    .join('\n\n');
  const componentCSS = generateComponentCSS(defaultTheme.components, UNIVERSAL_COMPONENT_SCOPE);
  for (const theme of restThemes) {
    if (generateComponentCSS(theme.components, UNIVERSAL_COMPONENT_SCOPE) !== componentCSS) {
      throw new Error(
        `Theme "${theme.meta.id}" has component recipes that differ from the default theme; ` +
          'component recipes must be appearance-independent (express differences as state tokens)',
      );
    }
  }

  return `/* Generated by theme system — do not edit manually */\n\n${rootBlock}\n\n${restBlocks}\n\n${componentCSS}\n`;
}
