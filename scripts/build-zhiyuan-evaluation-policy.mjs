import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDirectory = path.join(repositoryRoot, 'dist-eval');

await mkdir(outputDirectory, { recursive: true });
await build({
  entryPoints: [path.join(repositoryRoot, 'src/main/evaluation/zhiyuanEvaluationPolicy.ts')],
  outfile: path.join(outputDirectory, 'zhiyuan-evaluation-policy.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  sourcemap: true,
  packages: 'external',
  banner: { js: '// Generated by npm run build:eval-policy. Do not edit directly.' },
});

console.log('[EvaluationPolicy] built dist-eval/zhiyuan-evaluation-policy.mjs');
