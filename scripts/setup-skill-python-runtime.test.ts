import fs from 'node:fs';
import { createRequire } from 'node:module';
import os from 'node:os';
import path from 'node:path';
import { afterEach, expect, test } from 'vitest';

const require = createRequire(import.meta.url);
const {
  CORE_SKILL_IDS,
  buildDeltaLock,
  isPresetSkillDir,
  parseLockedPackages,
  selectCoreRequirements,
  validateSkillDependencyDeclarations,
} = require('./setup-skill-python-runtime.js') as {
  CORE_SKILL_IDS: Set<string>;
  buildDeltaLock: (lockText: string, corePackages: Map<string, string>) => string;
  isPresetSkillDir: (skillDir: string) => boolean;
  parseLockedPackages: (lockText: string) => Map<string, string>;
  selectCoreRequirements: (
    entries: Array<{ skillId: string; skillDir: string; requirementsPath: string }>,
  ) => Array<{ skillId: string }>;
  validateSkillDependencyDeclarations: (skillsRoot: string) => {
    ok: boolean;
    missing: string[];
  };
};

const temporaryDirectories: string[] = [];

afterEach(() => {
  for (const directory of temporaryDirectories.splice(0)) {
    fs.rmSync(directory, { recursive: true, force: true });
  }
});

test('recognizes standard-library imports used by bundled skill launchers', () => {
  const skillsRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'skill-python-declarations-'));
  temporaryDirectories.push(skillsRoot);
  const skillRoot = path.join(skillsRoot, 'fixture');
  fs.mkdirSync(skillRoot);
  fs.writeFileSync(
    path.join(skillRoot, 'launcher.py'),
    [
      'import hashlib',
      'import platform',
      'import runpy',
      'import tarfile',
      'import trimesh',
      '',
    ].join('\n'),
  );
  fs.writeFileSync(path.join(skillRoot, 'requirements.txt'), 'trimesh\n');

  expect(validateSkillDependencyDeclarations(skillsRoot)).toEqual({ ok: true, missing: [] });
});

test('treats local Python packages (directories with __init__.py) as local modules', () => {
  const skillsRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'skill-python-declarations-'));
  temporaryDirectories.push(skillsRoot);
  const scriptsRoot = path.join(skillsRoot, 'fixture', 'scripts');
  fs.mkdirSync(path.join(scriptsRoot, 'cover_lib'), { recursive: true });
  fs.writeFileSync(path.join(scriptsRoot, 'cover_lib', '__init__.py'), '');
  fs.writeFileSync(path.join(scriptsRoot, 'cover.py'), 'from cover_lib import render\n');

  expect(validateSkillDependencyDeclarations(skillsRoot)).toEqual({ ok: true, missing: [] });
});

test('keeps preset and non-core Skills out of the offline layer', () => {
  const entries = [
    {
      skillId: 'xlsx',
      skillDir: '/skills/xlsx',
      requirementsPath: '/skills/xlsx/requirements.txt',
    },
    {
      skillId: 'text-to-cad',
      skillDir: '/skills/zhiyuan-expert-manager/presets/cad/skills/text-to-cad',
      requirementsPath:
        '/skills/zhiyuan-expert-manager/presets/cad/skills/text-to-cad/requirements.txt',
    },
    {
      skillId: 'regression-insight',
      skillDir: '/skills/regression-insight',
      requirementsPath: '/skills/regression-insight/requirements.txt',
    },
  ];

  expect(selectCoreRequirements(entries).map(entry => entry.skillId)).toEqual(['xlsx']);
  expect(CORE_SKILL_IDS.has('xlsx')).toBe(true);
  expect(isPresetSkillDir(entries[1].skillDir)).toBe(true);
  expect(isPresetSkillDir(entries[0].skillDir)).toBe(false);
});

test('compiles a delta lock that drops packages already shipped in the layer', () => {
  const coreLock = [
    'numpy==2.5.4 \\',
    '    --hash=sha256:aaa',
    '    # via -r requirements.txt',
    'openpyxl==3.1.5 \\',
    '    --hash=sha256:bbb',
    '    # via -r requirements.txt',
  ].join('\n');
  const skillLock = [
    '# This file was autogenerated by uv',
    'numpy==2.5.4 \\',
    '    --hash=sha256:aaa',
    '    # via -r requirements.txt',
    'scipy==1.18.1 \\',
    '    --hash=sha256:ccc',
    '    # via -r requirements.txt',
    'statsmodels==0.15.0 \\',
    '    --hash=sha256:ddd',
    '    # via -r requirements.txt',
  ].join('\n');

  const delta = buildDeltaLock(skillLock, parseLockedPackages(coreLock));
  const deltaPackages = parseLockedPackages(delta);

  expect([...deltaPackages.keys()]).toEqual(['scipy', 'statsmodels']);
  expect(delta).not.toContain('numpy');
  // Hash pins must survive the rewrite: the overlay install stays reproducible.
  expect(delta).toContain('--hash=sha256:ccc');
});

test('keeps a differently pinned version so an overlay can shadow the layer', () => {
  const coreLock = 'pandas==2.3.3 \\\n    --hash=sha256:old\n';
  const skillLock = 'pandas==3.0.6 \\\n    --hash=sha256:new\n';

  const delta = parseLockedPackages(buildDeltaLock(skillLock, parseLockedPackages(coreLock)));

  expect(delta.get('pandas')).toBe('3.0.6');
});
